  static String generateFallbackHandle() {
    final adjective = _adjectives[_random.nextInt(_adjectives.length)];
    final firstLetter = adjective[0];

    final matchingAnimals =
        _animals.where((a) => a.startsWith(firstLetter)).toList();
    final animal = matchingAnimals.isNotEmpty
        ? matchingAnimals[_random.nextInt(matchingAnimals.length)]
        : _animals[_random.nextInt(_animals.length)];

    return '$adjective $animal';
  }

  static String toMentionTag(String handle) {
    if (handle.startsWith('@')) return handle;
    final compact = handle.replaceAll(' ', '');
    return '@$compact';
  }
